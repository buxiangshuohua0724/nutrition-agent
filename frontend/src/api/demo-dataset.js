/** 把一条 nutrition_value 行渲染成契约 3.3 的 NutritionRow */
function toRow(nv) {
  const meta = NUTRIENTS[nv.nutrientId]
  const missing = nv.valueStatus === 'MISSING'
  return {
    nutrientId: nv.nutrientId,
    nutrientCode: meta.code,
    nutrientName: meta.name,
    groupCode: meta.groupCode,
    displayOrder: meta.displayOrder,
    valueStatus: nv.valueStatus,
    unit: meta.unit,
    amount: missing ? null : nv.amount,
    displayText: missing ? '暂无数据' : `${nv.amount}`,
    source: SOURCE,
  }
}

